function T = nnls_results()
% Per-sample BSA concentrations, HARDCODED. Calculated by a separate NNLS solver.
% BSA_Drug_Delivery_NNLS_Cam_Ready.m 
% To refresh, rerun the NNLS script and paste the block it prints over this function.
% Columns: file name, geom, t_min, isPass, Vr_mL, C_BSA_ugmL
D = { ...
    "T0_B3C.csv", "C", 0, 0, 9.850898, -2.1199809779715002 ; ...
